import {mkdir,writeFile,readFile,copyFile} from 'node:fs/promises';
import {deploymentPlan} from '../src/deployment.mjs';
import {artifact,root} from './chain-helpers.mjs';
const args=process.argv.slice(2),option=n=>{const i=args.indexOf(n);return i<0?null:args[i+1];};
const deployer=option('--deployer'),rawNonce=option('--nonce');
if((deployer===null)!==(rawNonce===null))throw Error('Supply both --deployer and --nonce, or leave both blank. No private key is needed.');
const nonce=rawNonce===null?null:Number(rawNonce);if(nonce!==null&&(!Number.isSafeInteger(nonce)||nonce<0))throw Error('Nonce must be a safe nonnegative integer');
const config=JSON.parse(await readFile(root+'src/config.json','utf8'));
if(option('--fee-recipient'))throw Error('Initial fee recipient is the deployer; use --deployer and --nonce.');
const artifacts=Object.fromEntries(await Promise.all(['TapeMicroVault','TapeMicroMarket','TapeMicroMarketV2'].map(async n=>[n,await artifact(n)])));
const plan=await deploymentPlan(config,artifacts,deployer,nonce);
await mkdir(root+'output/deployment',{recursive:true});
await writeFile(root+'output/deployment/unsigned-plan.json',JSON.stringify(plan,null,2));
for(const n of Object.keys(artifacts))await copyFile(root+`artifacts/${n}.json`,root+`output/deployment/${n}.json`);
await copyFile(root+'artifacts/compiler-input.json',root+'output/deployment/compiler-input.json');
await copyFile(root+'artifacts/TapeMicroCustody.json',root+'output/deployment/TapeMicroCustody.json');
console.log('Prepared unsigned deployment artifacts in output/deployment. No transaction was sent.');
console.log(JSON.stringify({addresses:plan.addresses,feeRecipient:plan.feeRecipient,marketDataReady:!!plan.transactions[1].data}));
if(!plan.feeRecipient)console.log('Deployment wallet is not configured. Market deployment data is intentionally blank. No transaction was sent.');
